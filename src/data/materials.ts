type Draft = Omit<MaterialContent, "finishes" | "image" | "imageAlt"> & {
  image?: string;
  imageAlt?: string;
  finishes?: string[];
};

function metal(d: Draft): MaterialContent {
  return {
    ...d,
    family: "Metal",
    image: d.image ?? imgMetals,
    imageAlt: d.imageAlt ?? `${d.name} raw stock and machined components`,
    finishes: d.finishes ?? FINISH_METAL,
  };
}

function plastic(d: Draft): MaterialContent {
  return {
    ...d,
    family: "Plastic",
    image: d.image ?? imgPlastics,
    imageAlt: d.imageAlt ?? `${d.name} stock and machined plastic components`,
    finishes: d.finishes ?? FINISH_PLASTIC,
  };
}

